#!/usr/bin/env Rscript
#' Renders docs/CAPABILITY-MATRIX.md from bh_capability() and bh_conformance().
#'
#' The table lives in R/capability.R; this script only formats it, so the matrix, the tests
#' that assert its shape and the document that publishes it cannot drift apart silently.
#' Run from the package root: Rscript tools/render_capability_matrix.R
#'
#' The vector accounting it prints is measured by running the suite, not typed in, so the
#' document cannot claim a count the runner does not produce.

if (!requireNamespace("FAIRbioHeadersTools", quietly = TRUE)) stop("install the package first")
library(FAIRbioHeadersTools)

esc <- function(x) ifelse(is.na(x), "-", gsub("|", "\\|", x, fixed = TRUE))

m <- bh_capability()
run <- bh_conformance()
draft <- tryCatch(bh_draft_vectors(), error = function(e) NULL)
tab <- addmargins(table(run$results$format, run$results$status), quiet = TRUE)
fhgm <- tryCatch(suppressWarnings(bh_draft_fhgm_vectors()), error = function(e) NULL)
prov <- jsonlite::fromJSON("inst/VENDORED.json", simplifyVector = FALSE)

fmt_row <- function(fmt) {
  r <- run$results[run$results$format == fmt, ]
  reasons <- unique(r$reason[r$status == "not-run"])
  sprintf(
    "| %s | %d | pass %d / fail %d / error %d | %s |", fmt, nrow(r),
    sum(r$status == "pass"), sum(r$status == "fail"), sum(r$status == "error"),
    if (length(reasons)) gsub("not-run: ", "", paste(reasons, collapse = "; ")) else "-"
  )
}

header <- c(
  "# Capability matrix: type x operation x serialization x contract version",
  "",
  "Generated by `tools/render_capability_matrix.R` from `bh_capability()` and a live",
  "`bh_conformance()` run, so the numbers below are produced rather than asserted. The",
  "table in `R/capability.R` is the source of the cells;",
  "`tests/testthat/test-capability-and-links.R` checks its shape: every cell declares a",
  "support level, and every `not-supported-yet` names a reason and a tracker.",
  "",
  paste0(
    "Baseline: specification **", prov$conformance$ref, "** (tag commit `",
    substr(prov$conformance$commit, 1, 7),
    "`) - FHR 2.1, FHP 1.2, FHGFF3 1.2. FHT and FHGM are drafts under rule V7 and are ",
    "**not supported types**: no `schemaVersion`, no registry row, no w3id URL."
  ),
  "",
  "## Cells",
  "",
  paste0(
    "| type | type status | operation | serialization | contract versions | support | ",
    "reason / condition | tracker |"
  ),
  "| --- | --- | --- | --- | --- | --- | --- | --- |"
)
body_rows <- vapply(seq_len(nrow(m)), function(i) paste0(
  "| ", esc(m$header_type[i]), " | ", esc(m$type_status[i]), " | ", esc(m$operation[i]),
  " | ", esc(m$serialization[i]), " | ", esc(m$contract_versions[i]), " | **",
  esc(m$support[i]), "** | ", esc(m$blocker[i]), " | ", esc(m$tracker[i]), " |"
), "")

tail_lines <- c(
  "", "## Legend", "",
  "* `native` - implemented here and exercised by the shared-vector run below.",
  "* `draft-lane` - runs only with the rule V7 lane open, against bytes pinned by commit and",
  "  SHA-256, warning on every read. Reading a draft recognises a proposal; it does not",
  "  adopt one, and it is not a released-support claim.",
  "* `not-supported-yet` - a gap, with its reason and the issue that tracks it.",
  "* `not-applicable` - the combination does not exist in the specification.",
  "",
  "## Shared-vector accounting",
  "",
  paste0(
    "Suite: `", normalizePath(run$suite, mustWork = FALSE), "` (", run$vectors,
    " vectors, manifest sha256 `", substr(prov$conformance$manifest_sha256, 1, 16),
    "...`). Complete, unexpected results: ", run$failures, "."
  ),
  "", "| format | vectors | verdicts | reason where not run |",
  "| --- | --- | --- | --- |"
)
fmt_rows <- vapply(c("fasta", "gfa", "fhp-fasta", "fhgff3", "jsonld", "microdata"), fmt_row, "")
totals <- c(
  sprintf(
    "| **total** | **%d** | **%d pass, %d fail, %d not-run** | - |", run$vectors,
    sum(run$results$status == "pass"), sum(run$results$status == "fail"),
    sum(run$results$status == "not-run")
  ),
  "",
  "The rules a verdict does not settle are reported by `bh_rule_coverage()`: JSON-LD (J1-J9),",
  "microdata (M1-M5, R9) and the FHT development rule C2 need readers this package has not",
  "built, so their vectors stay not-run with the missing reader named instead of being",
  "passed or omitted. R11 and R14 are warning-only by specification, and the run reports",
  "which vectors had to emit them.",
  "",
  "## Draft evidence, kept separate",
  "",
  if (is.null(draft)) paste0(
    "The FHT development suite is not vendored in this build; run ",
    "`tools/vendor_upstream.R` to add it."
  ) else paste0(
    "FHT-Specification publishes its own development suite (", draft$vectors,
    " vectors, manifest sha256 `", substr(prov$draft_vectors$manifest_sha256, 1, 16),
    "...` at `", substr(prov$draft_vectors$commit, 1, 7), "`), which this package runs under ",
    "the lane with `bh_draft_vectors()`: ", sum(draft$results$status == "pass"), " pass, ",
    sum(draft$results$status == "fail"), " fail. It is **draft evidence and never part of ",
    "the 291** - its own manifest says its expectations are \"derived from the rule text, ",
    "never from an implementation under test\", and rule V7 keeps pre-release evidence ",
    "separate from release claims."
  ),
  "",
  if (is.null(fhgm)) paste0(
    "The FHGM development suite is not vendored in this build."
  ) else paste0(
    "FHGM-Specification publishes its own development suite (", fhgm$vectors,
    " vectors, manifest sha256 `", substr(prov$draft_fhgm_vectors$manifest_sha256, 1, 16),
    "...`), whose files record four independent layers each. ",
    "`bh_draft_fhgm_vectors()` compares the two this package evaluates natively - base (the ",
    "released FHGFF3 contract over the parsed header) and checksum - on all ", fhgm$vectors,
    " vectors, and the model layer where a vector's rules are record-shape and transport ",
    "only (K1/K2): ", sum(fhgm$results$status == "pass"), " comparable and agreeing, ",
    sum(fhgm$results$status == "not-run"),
    " reported not-run naming the checker rule it lacks (K3-K6, B1). The gff3 feature layer ",
    "is never run here: it belongs to gff3-validator."
  ),
  "",
  "## Not verified by this document",
  "",
  "* Linux and Windows builds of the vendored digest core, and of `V8`/`jsonvalidate`, are",
  "  exercised only where CI runs them; see `docs/DIGEST.md`.",
  "* JSON-LD and microdata conformance is not measured at all, because the readers do not",
  "  exist yet - the not-run rows above are the claim.",
  "* No writer behaviour: this package does not produce, strip or convert headers yet.",
  ""
)

writeLines(c(header, body_rows, tail_lines, fmt_rows, totals),
  "docs/CAPABILITY-MATRIX.md"
)
cat("wrote docs/CAPABILITY-MATRIX.md:", nrow(m), "cells\n")
