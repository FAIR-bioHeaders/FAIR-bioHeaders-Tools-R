#' Default-behavior fingerprint (test-support machinery, not user API)
#'
#' The golden file at `tests/testthat/reference/default-behavior-v0.6.0.json` is a
#' fingerprint of what the default reading (lane closed, released contracts) does with
#' every shared vector and every selection rule, generated once from the verified
#' implementation and compared thereafter. The claim it protects is the one the draft
#' lane and any future refactor must never break: with `draft = FALSE` the reading is
#' exactly the reading that was accepted against the shared suite. Unlike the Java
#' library's golden, there is no prior commit of this package to generate it from - the
#' published `main` before this work was an empty stub - so the golden is anchored at
#' the first implementation that passed the shared vectors, and guards every change
#' after it. It is never regenerated by a test: regeneration is a reviewed, deliberate
#' act recorded in the file's own metadata.
#'
#' What is pinned per vector, chosen to survive message-text churn while capturing
#' behaviour: the verdict, the computed checksum and hashed-byte count, the normalized
#' rule/selection outcome, the rule code of every issue and warning (first token), and
#' the SHA-256 of the canonical JSON the contract validator received. A change in any
#' of those moves the golden and must be explained.
#'
#' @name fingerprint
NULL

#' @noRd
.bh_golden_path <- function() {
  root <- tryCatch(testthat::test_path(), error = function(e) NULL)
  cands <- c(
    Sys.getenv("BH_GOLDEN_FILE", unset = NA_character_),
    if (!is.null(root)) file.path(root, "reference", "default-behavior-v0.6.0.json"),
    "tests/testthat/reference/default-behavior-v0.6.0.json",
    "reference/default-behavior-v0.6.0.json"
  )
  cands <- cands[!is.na(cands) & nzchar(cands)]
  for (c in cands) if (file.exists(c)) return(c)
  bh_abort("golden", paste0(
    "the default-behavior golden file was not found (looked in: ",
    paste(sQuote(unique(cands)), collapse = ", "),
    "). It lives at tests/testthat/reference/; a missing golden is an acceptance ",
    "failure, not a skip."
  ))
}

# First token of a diagnostic: "R4:", "rule V5 ...", "R14:", "empty-required: ...",
# "FHT: warning: ...". Enough to identify WHICH check fired without pinning prose.
.bh_issue_code <- function(msg) {
  m <- regmatches(msg, regexec("^([^ :]+)[ ]?[^:]*:", msg))[[1L]]
  if (length(m)) return(m[[2L]])
  substr(msg, 1L, 24L)
}

#' @noRd
.bh_fingerprint <- function(suite = NULL) {
  dir <- .bh_suite_dir(suite)
  man <- jsonlite::fromJSON(rawToChar(.bh_read_all(file.path(dir, "manifest.json"))),
    simplifyVector = FALSE
  )
  vectors <- lapply(man$vectors, function(v) {
    fmt <- v$format
    if (!fmt %in% .bh_supported_formats) {
      return(list(
        id = v$id, format = fmt, expected = v$expected, ran = FALSE,
        reason = .bh_not_run_reasons[[fmt]] %||% "not-run: no native reader"
      ))
    }
    a <- .bh_analyze(file.path(dir, v$file), format = fmt, draft = FALSE)
    list(
      id = v$id, format = fmt, expected = v$expected, ran = TRUE,
      observed = if (isTRUE(a$valid)) "valid" else "invalid",
      checksum_recorded = a$checksum$recorded,
      checksum_computed = a$checksum$computed,
      checksum_bytes = a$checksum$bytes,
      late_header_lines = a$checksum$late_header_lines,
      selection = list(
        rule = a$selection$rule, header_type = a$selection$header_type,
        release = a$selection$release, schema_version = a$selection$schema_version,
        status = a$selection$status
      ),
      # radix: byte order, so the golden reads the same under any locale's collation
      issue_codes = sort(vapply(a$issues, .bh_issue_code, "", USE.NAMES = FALSE),
        method = "radix"),
      warning_codes = sort(vapply(a$warnings, .bh_issue_code, "", USE.NAMES = FALSE),
        method = "radix"),
      record_json_sha256 = if (is.null(a$record)) NA_character_ else
        .bh_sha256_hex(charToRaw(.bh_record_json(a$record)))
    )
  })
  # The selection rule table: V1-V6 outcomes for the citations that exercise them,
  # read off released registry data. Draft-lane behaviour is deliberately absent:
  # this is the fingerprint of the DEFAULT (draft = FALSE) path.
  raw_main <- c(
    fhr = "https://raw.githubusercontent.com/FAIR-bioHeaders/FAIR-bioHeaders-Specification/main/fhr.json",
    fhp = "https://raw.githubusercontent.com/FAIR-bioHeaders/FAIR-bioHeaders-Specification/main/fhp.json",
    fhgff3 = "https://raw.githubusercontent.com/FAIR-bioHeaders/FAIR-bioHeaders-Specification/main/fhgff3.json"
  )
  probes <- list()
  add <- function(label, sel) {
    probes[[label]] <<- list(
      rule = sel$rule, header_type = sel$header_type, release = sel$release,
      schema_version = sel$schema_version, status = sel$status,
      warned = length(sel$warnings) > 0L
    )
  }
  for (f in names(raw_main)) add(paste0("raw-main-", f), bh_select(raw_main[[f]]))
  for (rel in c("v0.3.1", "v0.4.0", "v0.5.0", "v0.6.0")) {
    for (f in names(raw_main)) {
      add(paste0("raw-tag-", rel, "-", f),
        bh_select(sub("/main/", paste0("/", rel, "/"), raw_main[[f]], fixed = TRUE))
      )
    }
    for (t in names(.bh_types_by_file)) {
      add(paste0("w3id-", rel, "-", t),
        bh_select(sprintf("https://w3id.org/fair-bioheaders/%s/%s", t, rel))
      )
    }
  }
  add("v5-arbitrary", bh_select("https://example.org/some/other/schema.json"))
  add("v5-fht-raw-main-lane-closed",
    bh_select("https://raw.githubusercontent.com/FAIR-bioHeaders/FHT-Specification/main/fht.json")
  )
  add("v6-number-one", bh_select(raw_main[["fhr"]], schema_version = 1))
  add("v6-string-one", bh_select(raw_main[["fhr"]], schema_version = "1"))
  add("v4-unknown-release",
    bh_select("https://w3id.org/fair-bioheaders/fhr/v9.9.9")
  )
  structure(
    list(
      fingerprintVersion = 1L,
      configuration = "default: released contracts only, draft lane closed",
      generated = "2026-11-14",
      generatedFrom = list(
        package = "FAIRbioHeadersTools 0.1.0",
        baseline = "specification v0.6.0 (tag object ab7e3ddd, commit 0ae18b0)"
      ),
      suite = list(
        manifest_sha256 = .bh_vendored()$conformance$manifest_sha256,
        vectors = length(man$vectors),
        ran = sum(vapply(vectors, function(x) isTRUE(x$ran), logical(1L)))
      ),
      engine = .bh_engine,
      vectors = vectors,
      selectionProbes = probes
    )
  )
}

# Compares a fingerprint against the golden, returning the difference list (not an
# error) so both the test and the CI script can phrase the same finding.
#' @noRd
.bh_golden_diff <- function(got, want) {
  diffs <- character()
  changes_path <- file.path(dirname(.bh_golden_path()), "reader-policy-changes.json")
  if (file.exists(changes_path)) {
    changes <- jsonlite::fromJSON(changes_path, simplifyVector = FALSE)$changes
    for (change in changes) {
      i <- match(change$id, vapply(want$vectors, function(x) x$id, ""))
      if (is.na(i) || !identical(want$vectors[[i]], change$from)) {
        diffs <- c(diffs, paste0("policy overlay predecessor differs: ", change$id))
      } else want$vectors[[i]] <- change$to
    }
  } else diffs <- c(diffs, "missing explicit reader-policy golden delta")
  brief <- function(x) {
    s <- tryCatch(
      as.character(jsonlite::toJSON(x, auto_unbox = TRUE)),
      error = function(e) paste(class(x), length(x))
    )
    substr(paste(s, collapse = ""), 1L, 140L)
  }
  cmp <- function(path, g, w) {
    if (!identical(g, w)) {
      diffs <<- c(diffs, paste0(path, ": got ", brief(g), " want ", brief(w)))
    }
  }
  for (k in c("fingerprintVersion", "configuration", "engine")) cmp(k, got[[k]], want[[k]])
  wv <- vapply(want$vectors, function(x) x$id, "")
  for (v in got$vectors) {
    i <- match(v$id, wv)
    if (is.na(i)) {
      diffs <- c(diffs, paste0("vector ", v$id, ": absent from the golden"))
      next
    }
    w <- want$vectors[[i]]
    for (k in names(v)) cmp(paste0(v$id, ".", k), v[[k]], w[[k]])
  }
  if (length(got$vectors) != length(want$vectors)) {
    diffs <- c(diffs, paste0(
      "vector count: got ", length(got$vectors), " want ", length(want$vectors)
    ))
  }
  for (k in names(got$selectionProbes)) {
    if (is.null(want$selectionProbes[[k]])) {
      diffs <- c(diffs, paste0("probe ", k, ": absent from the golden"))
    } else {
      for (f in names(got$selectionProbes[[k]])) {
        cmp(paste0("probe.", k, ".", f), got$selectionProbes[[k]][[f]],
          want$selectionProbes[[k]][[f]]
        )
      }
    }
  }
  diffs
}

# Writes a key=value properties receipt when the named env var points somewhere;
# silent no-op otherwise (local runs and R CMD check write nothing).
#' @noRd
.bh_receipt <- function(env_var, fields) {
  path <- Sys.getenv(env_var, unset = "")
  if (!nzchar(path)) return(invisible(NULL))
  lines <- vapply(names(fields), function(k) paste0(k, "=", fields[[k]]), "")
  writeLines(lines, path)
  invisible(path)
}
